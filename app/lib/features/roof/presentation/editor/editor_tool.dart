/// Herramientas del editor del techo.
enum EditorTool {
  /// Línea de calibración (escala).
  calibrate,

  /// Segunda línea de verificación de la escala.
  verify,

  /// Orientación al norte.
  north,

  /// Trazar un plano (polígono).
  draw,

  /// Colocar obstáculos.
  obstacle,

  /// Pasillos de mantenimiento.
  walkway,

  /// Tocar para elegir y editar planos u obstáculos.
  select,
}
